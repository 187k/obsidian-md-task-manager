let current: Record<I18nKey, string> = en;
let currentLang: "en" | "ru" = "en";

export function setLanguage(lang: "auto" | "en" | "ru"): void {
	let resolved = lang;
	if (resolved === "auto") {
		const obsidianLang = window.localStorage.getItem("language") ?? "en";
		resolved = obsidianLang.startsWith("ru") ? "ru" : "en";
	}
	currentLang = resolved;
	current = resolved === "ru" ? ru : en;
}

export function getLanguage(): "en" | "ru" {
	return currentLang;
}

export function t(key: I18nKey, vars?: Record<string, string | number>): string {
	let s = current[key] ?? en[key] ?? key;
	if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
	return s;
}
